        // TAMBAH SETORAN (ADMIN LOGIC)
        function handleTambahSetoran(e) {
            e.preventDefault();
            if (!isAdmin) return;

            const siswaNo = Number(document.getElementById('input-setoran-siswa').value);
            const tanggal = document.getElementById('input-setoran-tanggal').value;
            const nominalBaru = Number(document.getElementById('input-setoran-nominal').value);
            const catatan = document.getElementById('input-setoran-catatan').value || '-';

            if (!siswaNo || !tanggal || nominalBaru <= 0) {
                alert('Aplikasi Menolak: Mohon lengkapi semua kolom setoran dengan benar!');
                return;
            }

            const siswaIdx = siswaList.findIndex(s => s.no === siswaNo);
            if (siswaIdx === -1) return;

            // Akumulasi nominal & update tanggal
            siswaList[siswaIdx].nominal = (Number(siswaList[siswaIdx].nominal) || 0) + nominalBaru;
            siswaList[siswaIdx].tanggal = tanggal;

            // Log Histori Transaksi
            const now = new Date();
            const formattedNow = `${now.toISOString().split('T')[0]} ${String(now.getHours()).padStart(2,'0')}:${String(now.getMinutes()).padStart(2,'0')}`;

            historiList.push({
                id: Date.now(),
                inputAt: formattedNow,
                tanggal: tanggal,
                tipe: 'MASUK',
                subjek: siswaList[siswaIdx].nama_siswa,
                nominal: nominalBaru,
                resi: catatan
            });

            saveState();

            // Reset Form Input
            document.getElementById('input-setoran-nominal').value = '';
            document.getElementById('input-setoran-catatan').value = '';
            
            alert(`Setoran Rp ${nominalBaru.toLocaleString('id-ID')} untuk ${siswaList[siswaIdx].nama_siswa} berhasil disimpan!`);
        }

