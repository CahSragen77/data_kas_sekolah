        function renderKPIs() {
            const totalSiswa = siswaList.length;
            const totalL = siswaList.filter(s => s.gender === 'L').length;
            const totalP = siswaList.filter(s => s.gender === 'P').length;

            const totalMasuk = siswaList.reduce((acc, curr) => acc + (Number(curr.nominal) || 0), 0);
            const totalKeluar = kasKeluarList.reduce((acc, curr) => acc + (Number(curr.nominal) || 0), 0);
            const saldoAkhir = totalMasuk - totalKeluar;
            const totalBulan = Math.floor(totalMasuk / 10000);

            document.getElementById('kpi-total-siswa').innerText = totalSiswa;
            document.getElementById('kpi-gender-ratio').innerText = `L: ${totalL} | P: ${totalP}`;

            document.getElementById('kpi-total-masuk').innerText = formatRupiah(totalMasuk);
            document.getElementById('kpi-total-bulan').innerText = `Setara ${totalBulan} Bulan Iuran`;

            document.getElementById('kpi-total-keluar').innerText = formatRupiah(totalKeluar);
            document.getElementById('kpi-count-keluar').innerText = `${kasKeluarList.length} Transaksi Pengeluaran`;

            document.getElementById('kpi-saldo-akhir').innerText = formatRupiah(saldoAkhir);
        }

        function renderSiswaTable() {
            const tbody = document.getElementById('tbody-siswa');
            tbody.innerHTML = '';

            const searchKey = document.getElementById('search-siswa').value.toLowerCase();
            const filterGen = document.getElementById('filter-gender').value;
            const filterStat = document.getElementById('filter-status').value;

            const filtered = siswaList.filter(s => {
                const matchSearch = s.nama_siswa.toLowerCase().includes(searchKey) || s.nis.toLowerCase().includes(searchKey);
                const matchGender = filterGen === '' || s.gender === filterGen;
                
                let matchStatus = true;
                if (filterStat === 'lunas') matchStatus = s.nominal > 0;
                if (filterStat === 'belum') matchStatus = s.nominal === 0;

                return matchSearch && matchGender && matchStatus;
            });

            if (filtered.length === 0) {
                tbody.innerHTML = `<tr><td colspan="8" class="text-center py-6 text-slate-400">Data siswa tidak ditemukan.</td></tr>`;
                return;
            }

            filtered.forEach((s, idx) => {
                const nominal = Number(s.nominal) || 0;
                const totalBulan = Math.floor(nominal / 10000);
                const ketBulan = totalBulan > 0 ? `${totalBulan} bulan` : '0 bulan';

                const tr = document.createElement('tr');
                tr.className = 'hover:bg-slate-50/80 transition';
                tr.innerHTML = `
                    <td class="py-2.5 px-4 text-center font-bold text-slate-400">${idx + 1}</td>
                    <td class="py-2.5 px-4 font-mono text-slate-500">${s.nis}</td>
                    <td class="py-2.5 px-4 font-bold text-slate-800">${s.nama_siswa}</td>
                    <td class="py-2.5 px-4 text-center">
                        <span class="px-2 py-0.5 rounded text-[10px] font-extrabold ${s.gender === 'L' ? 'bg-blue-100 text-blue-700' : 'bg-pink-100 text-pink-700'}">${s.gender}</span>
                    </td>
                    <td class="py-2.5 px-4 text-right font-bold ${nominal > 0 ? 'text-brand-600' : 'text-slate-400'}">${formatRupiah(nominal)}</td>
                    <td class="py-2.5 px-4 text-center">
                        <span class="px-2 py-1 rounded-md text-xs font-semibold ${totalBulan > 0 ? 'bg-emerald-50 text-emerald-700 border border-emerald-200' : 'bg-slate-100 text-slate-500'}">${ketBulan}</span>
                    </td>
                    <td class="py-2.5 px-4 text-slate-500">${s.tanggal || '-'}</td>
                    <td class="py-2.5 px-4 text-center admin-only ${isAdmin ? '' : 'hidden'}">
                        <div class="flex items-center justify-center gap-1">
                            <button onclick="openEditSiswaModal(${s.no})" class="p-1.5 text-blue-600 hover:bg-blue-50 rounded" title="Edit Data"><i class="fa-solid fa-pen-to-square"></i></button>
                            <button onclick="resetSiswaNominal(${s.no})" class="p-1.5 text-rose-600 hover:bg-rose-50 rounded" title="Reset Nominal ke 0"><i class="fa-solid fa-arrow-rotate-left"></i></button>
                        </div>
                    </td>
                `;
                tbody.appendChild(tr);
            });
        }

